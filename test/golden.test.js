// Every file and folder under `dir` gets the same mtime (links are left as
// they are), so each project's modifiedAt comes out the same every run.
function stampTree(dir, t = FIXED - 120 * MIN) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isSymbolicLink()) continue;
    if (e.isDirectory()) stampTree(full, t);
    fs.utimesSync(full, t / 1000, t / 1000);
  }
  fs.utimesSync(dir, t / 1000, t / 1000);
}

