// Paths in the world, whatever the temp folder and port, as <world>.
const forms = [...new Set([world.root, world.root.replace(/\\/g, "/"), pathKey(world.root)])];
const canon = (x) => {
  if (typeof x === "string") {
    let s = x;
    for (const f of forms) s = s.split(f).join("<world>");
    s = s.replace(/\/private<world>/g, "<world>");
    return s.includes("<world>") || s.includes("~") ? s.replace(/\\/g, "/") : s;
  }
  if (Array.isArray(x)) return x.map(canon);
  return x && typeof x === "object" ? Object.fromEntries(Object.entries(x).map(([k, v]) => [canon(k), k === "score" && typeof v === "number" ? Number(v.toPrecision(12)) : canon(v)])) : x;
};

function golden(name, actual) {
  const file = path.join(here, "golden", `${name}.json`);
  const data = canon(JSON.parse(JSON.stringify(actual)));
  if (process.env.XENONET_GOLDEN === "update") {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, JSON.stringify(data, null, 1) + "\n");
    return;
  }
  const expected = canon(JSON.parse(fs.readFileSync(file, "utf8")));
  try {
    assert.deepStrictEqual(data, expected);
  } catch (err) {
    const out = path.join(here, "..", ".xenonet", `golden-${name}.json`);
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, JSON.stringify(data, null, 1) + "\n");
    err.message = `${name} differs from test/golden/${name}.json (what came out is in .xenonet/golden-${name}.json)\n${err.message}`;
    throw err;
  }
}

