// Every file's mtime, set: a transcript's is its last line's time; the
// rest, two hours before the clock.
function setTimes() {
  const lastTime = (file) => {
    const lines = fs.readFileSync(file, "utf8").trim().split("\n").reverse();
    for (const l of lines) {
      const t = Date.parse((() => { try { return JSON.parse(l)?.timestamp; } catch { return null; } })());
      if (Number.isFinite(t)) return t;
    }
    return FIXED - MIN;
  };
  const walk = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) walk(full);
      const t = e.isFile() && e.name.endsWith(".jsonl") ? lastTime(full) : FIXED - 120 * MIN;
      fs.utimesSync(full, t / 1000, t / 1000);
    }
  };
  walk(world.root);
}

